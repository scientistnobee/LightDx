#!/usr/bin/env python3
"""Illuminance (lux) weights for the AS7341 (LightDX).

Finds non-negative weights v_i so that  L = sum_i v_i * cnt_i  is proportional to illuminance,
i.e. to  integral E(l) V(l) dl  (V = CIE photopic, Wyman et al. 2013 analytic fit), over a mix of
daylight, incandescent and rough synthetic LED/fluorescent spectra (relative-error fit).

Reuses the (PLACEHOLDER) channel responsivities and illuminant models from ppix_weights.py.
Result is in ARBITRARY units: multiply by LUX_K (calibrate against a lux meter) to get lux.
Writes firmware/capsule_serial_test/lux_weights.h.
"""
import os
import numpy as np
from scipy.optimize import nnls

import ppix_weights as pw

WL, HERE = pw.WL, pw.HERE
HEADER_OUT = os.path.join(HERE, "..", "firmware", "capsule_serial_test", "lux_weights.h")


def v_lambda(wl):
    """CIE 1931 photopic luminosity, multi-lobe Gaussian fit (Wyman, Sloan, Shirley 2013)."""
    def lobe(a, mu, s1, s2):
        s = np.where(wl < mu, s1, s2)
        return a * np.exp(-0.5 * ((wl - mu) / s) ** 2)
    return lobe(0.821, 568.8, 46.9, 40.5) + lobe(0.286, 530.9, 16.3, 31.1)


def main():
    pw.write_placeholders()
    _, rbody = pw.load_table("as7341_response.csv")
    R = pw.on_grid(rbody)[:, :8]
    basis = np.loadtxt(os.path.join(pw.DATA, "cie_daylight_basis.csv"), delimiter=",", skiprows=2)
    V = v_lambda(WL)

    spectra = {f"D{c}": pw.daylight(c, basis) for c in [4000, 5000, 6500, 10000, 15000]}
    spectra.update(pw.synthetic_lamps())

    rows, rhs = [], []
    for s in spectra.values():
        y = np.trapezoid(V * s, WL)
        rows.append(np.trapezoid(R * s[:, None], WL, axis=0) / y)  # relative-error rows
        rhs.append(1.0)
    w, _ = nnls(np.array(rows), np.array(rhs), maxiter=10000)

    print("Lux weights v_i (arbitrary units):")
    for n, v in zip(pw.CH, w):
        print(f"  {n:8s} {v:.6g}")
    print(f"\n  {'illuminant':24s} {'error %':>8s}")
    for name, s in spectra.items():
        y = np.trapezoid(V * s, WL)
        m = float(np.dot(w, np.trapezoid(R * s[:, None], WL, axis=0)))
        print(f"  {name:24s} {100 * (m - y) / y:8.1f}")

    with open(HEADER_OUT, "w") as f:
        f.write("// GENERATED by analysis/lux_weights.py -- do not edit by hand.\n"
                "// L = sum_i W_LUX[i] * cnt_i (F1..F8), proportional to illuminance; lux = LUX_K * L.\n"
                "// Based on PLACEHOLDER channel responsivities. Calibrate LUX_K against a lux meter.\n"
                "#pragma once\n")
        f.write("static const float W_LUX[8] = {" + ", ".join(f"{v:.8e}f" for v in w) + "};\n")
    print("\nWrote", os.path.normpath(HEADER_OUT))


if __name__ == "__main__":
    main()
